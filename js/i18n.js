const SKILL_NAMES = {
  en: { garden: 'Gardening', forage: 'Foraging', craft: 'Crafting', engineer: 'Engineering', fish: 'Fishing', cook: 'Cooking' },
  id: { garden: 'Berkebun', forage: 'Meramu', craft: 'Kerajinan', engineer: 'Teknik', fish: 'Memancing', cook: 'Memasak' },
};

let lang = 'en';
export const setLang = (value) => {
  lang = value === 'id' ? 'id' : 'en';
  document.documentElement.lang = lang;
};
export const getLang = () => lang;

export function t(key, vars = {}) {
  const text = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] !== undefined ? vars[name] : ''));
}
export const itemName = (id) => (ITEMS[id] ? (lang === 'id' ? ITEMS[id].id : ITEMS[id].en) : id);
export const skillName = (id) => SKILL_NAMES[lang][id] || id;
export const islandName = (id) => {
  const island = ISLANDS.find((i) => i.id === id);
  return island ? (lang === 'id' ? island.idn : island.en) : '';
};
export const projectName = (id) => {
  const p = PROJECTS.find((x) => x.id === id);
  return p ? (lang === 'id' ? p.id_ : p.en) : id;
};
export const projectBody = (id) => {
  const p = PROJECTS.find((x) => x.id === id);
  return p ? (lang === 'id' ? p.idBody : p.enBody) : '';
};
export const npcBlurb = (id) => (lang === 'id' ? NPCS[id].idn : NPCS[id].en);
export const questName = (q) => (lang === 'id' ? q.idn : q.en);
export const questHint = (q) => (lang === 'id' ? q.hintId : q.hint);
export const buffText = (id) => (lang === 'id' ? BUFFS[id].id : BUFFS[id].en);
export const phraseText = (id) => {
  const p = PHRASES.find((x) => x.id === id);
  return p ? (lang === 'id' ? p.idn : p.en) : '';
};
export const allStrings = STRINGS;
